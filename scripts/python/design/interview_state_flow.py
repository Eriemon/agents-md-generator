# 远程流程关闭：公开该职责的状态转换入口
def answer_remote_install_confirmation(project: Path, state: dict[str, Any], payload: dict[str, Any]) -> dict[str, Any]:
    """处理远程依赖安装确认。

    参数：project 为项目根；state 为门禁状态；payload 为安装或禁用选择。
    返回：安装等待阶段或关闭远程后的交互载荷。
    异常：确认值缺失、非法或拒绝安装时输出诊断并抛出 SystemExit(1)。
    数组契约：shape 由门禁字段决定，dtype 为 JSON 映射，unit 不适用。
    """

    # 说明该控制语句在设计访谈状态流程中的分支职责。
    value_remote_enabled = payload.get(USE_REMOTE_SERVER_KEY)  # 用户提交的远程能力开关原值

    # 仅布尔 false 表示用户明确关闭远程能力。
    if isinstance(value_remote_enabled, bool) and not value_remote_enabled:

        # 远程安装确认：用户关闭远程能力后继续本地访谈
        return disable_remote_gate_and_continue(project, state)

    # 布尔确认决定继续安装门禁还是退出远程流程。
    if REMOTE_INSTALL_CONFIRM_KEY not in payload or not isinstance(payload[REMOTE_INSTALL_CONFIRM_KEY], bool):

        # 远程安装确认：将校验错误输出到机器可读协议
        emit_json(
            interactive_payload(
                project,
                state,
                errors=[f"{REMOTE_INSTALL_CONFIRM_KEY} must be provided as true or false"],
            )
        )

        # 远程安装确认：拒绝继续处理已经确认的非法状态
        raise SystemExit(1)

    # 远程安装确认：依据当前合同条件选择后续状态分支
    if payload[REMOTE_INSTALL_CONFIRM_KEY]:

        # 用户同意安装时更新门禁确认标志。
        dict_gate = remote_gate_payload(state)  # 远程安装确认：读取远程门禁的持久化载荷

        # 远程安装确认：建立后续状态判定所需的具体中间量
        dict_gate["install_confirmed"] = True  # 远程安装确认：确认用户已授权安装远程依赖

        # 将更新后的安装授权写回状态载荷。
        set_remote_gate_payload(state, dict_gate)

        # 安装授权完成后等待外部安装完成信号。
        state["status"] = "awaiting_remote_install_completion"  # 远程安装确认：等待远程依赖安装完成证据

        # 远程安装确认：在响应前持久化本次状态迁移
        write_state(project, state)

        # 远程安装确认：返回与最新持久化状态一致的交互响应
        return interactive_payload(project, state)

    # remote install 被取消时向调用方返回可恢复的阻断原因。
    list_errors = [  # 远程依赖缺失时返回给交互层的阻断原因
        "remote server flow remains blocked until erie-remote-ssh is installed "  # 远程依赖缺失说明
        "or use_remote_server is changed to false"  # 关闭远程流程的替代动作
    ]

    # 将阻断原因写入交互响应，保持状态文件不被误判为完成。
    emit_json(interactive_payload(project, state, errors=list_errors))

    # 用户拒绝安装但未关闭远程能力时保持阻断。
    raise SystemExit(1)

# 远程安装确认：公开该职责的状态转换入口
def answer_remote_configuration_confirmation(
    project: Path,
    state: dict[str, Any],
    payload: dict[str, Any],
) -> dict[str, Any]:
    """处理远程服务器配置方式确认。

    参数：project 为项目根；state 为门禁状态；payload 为配置模式或禁用选择。
    返回：配置等待阶段或关闭远程后的交互载荷。
    异常：配置模式非法或取消配置时输出诊断并抛出 SystemExit(1)。
    数组契约：shape 由配置字段决定，dtype 为 JSON 映射，unit 不适用。
    """

    # 显式关闭远程能力时立即返回本地访谈路径。
    value_remote_enabled = payload.get(USE_REMOTE_SERVER_KEY)  # 配置阶段收到的远程能力开关

    # 明确禁用时清理门禁，缺失值仍由配置合同处理。
    if isinstance(value_remote_enabled, bool) and not value_remote_enabled:

        # 远程配置确认：用户关闭远程能力后继续本地访谈
        return disable_remote_gate_and_continue(project, state)

    # 远程配置确认：建立后续状态判定所需的具体中间量
    str_mode = str(payload.get(REMOTE_CONFIGURATION_MODE_KEY, "")).strip().lower()  # 远程配置确认：记录用户选择的远程配置方式

    # cancel 仅取消本次配置，不等价于关闭远程能力。
    if str_mode not in {"guided", "manual", "cancel"}:

        # 远程配置确认：将校验错误输出到机器可读协议
        emit_json(
            interactive_payload(
                project,
                state,
                errors=[f"{REMOTE_CONFIGURATION_MODE_KEY} must be guided, manual, or cancel"],
            )
        )

        # 远程配置确认：拒绝继续处理已经确认的非法状态
        raise SystemExit(1)

    # 远程配置确认：依据当前合同条件选择后续状态分支
    if str_mode == "cancel":

        # 取消配置时构造可恢复的阻断说明。
        list_errors = [  # 远程配置未完成时返回给交互层的阻断原因
            "remote server flow remains blocked until configuration is completed "  # 远程配置缺失说明
            "or use_remote_server is changed to false"  # 远程配置确认：保存当前分支产生的数据
        ]

        # 通过交互协议展示继续配置或关闭远程能力两种选择。
        emit_json(interactive_payload(project, state, errors=list_errors))

        # 非零退出码阻止调用方把取消配置误判为完成。
        raise SystemExit(1)

    # 读取现有门禁载荷以保留发现和候选证据。
    dict_gate = remote_gate_payload(state)  # 远程配置确认：读取远程门禁的持久化载荷

    # 在原载荷中登记 guided 或 manual 选择。
    dict_gate["configuration_mode"] = str_mode  # 后续配置步骤采用的执行模式

    # 将配置模式与已有门禁证据一并写回主状态。
    set_remote_gate_payload(state, dict_gate)

    # 模式确认完成后等待实际配置完成证据。
    state["status"] = "awaiting_remote_configuration_completion"  # 远程配置确认：等待远程服务器配置完成证据

    # 远程配置确认：在响应前持久化本次状态迁移
    write_state(project, state)

    # 远程配置确认：返回与最新持久化状态一致的交互响应
    return interactive_payload(project, state)

# 服务器路由确认负责校验并持久化任务类型到服务器的映射。
