# 定义 normalize_intent 的设计访谈状态处理入口。
def normalize_intent(value: Any) -> str:
    """把外部输入的执行意图收敛到状态机支持的两种模式。

    # 补充设计访谈状态代码段的职责说明。
    参数:
        value: CLI、JSON 状态或调用方传入的意图值。

    # 补充设计访谈状态代码段的职责说明。
    返回:
        ``read_only`` 或 ``write``；未知值按写入流程处理，保持历史默认行为。
    """

    # 先做字符串归一化，避免 None、空白和大小写差异污染状态文件。
    intent = str(value or "write").strip().lower()  # 访谈流程意图

    # 只读流程是唯一的特殊分支，其余输入都回落到写入流程。
    return "read_only" if intent == "read_only" else "write"


# 定义 review_policy_for_state 的设计访谈状态处理入口。
def review_policy_for_state(state: dict[str, Any], status: str | None = None) -> str:
    """根据当前状态判断是否需要子代理复核。

    # 补充设计访谈状态代码段的职责说明。
    参数:
        state: 设计访谈状态字典。
        status: 调用方临时指定的状态；为空时读取状态文件中的 ``status``。

    # 补充设计访谈状态代码段的职责说明。
    返回:
        复核策略标识，供交互 payload 和写入阶段判断审核边界。
    
        数组契约:
            shape/维度: 本函数处理 AGENTS 状态、JSON 记录或文件路径，不接收数值数组，数组维度不适用。
            dtype/类型: 输入输出由 dict、list、str、Path 等 Python 业务类型约束，非 ndarray dtype。
            unit/单位: 无物理量单位，字段含义以 AGENTS 治理配置和状态文件 schema 为准。
    """

    # 使用显式覆盖状态支持预览分支，不提前修改持久化状态。
    resolved_status = status or str(state.get("status", "collecting_group"))  # 当前状态名

    # 已完成的只读流程不能再要求写入式复核。
    if resolved_status == "completed_read_only":

        # 返回 review_policy_for_state 的访谈状态载荷。
        return "read_only_no_subagent_review"

    # 进入设计复核后的写入流程必须保留子代理复核边界。
    if resolved_status in {"awaiting_design_review", "awaiting_review_rework", "completed"}:

        # 返回 review_policy_for_state 的访谈状态载荷。
        return "subagent_review_required"

    # 只读意图在未进入写入复核前始终走轻量确认策略。
    if normalize_intent(state.get("intent")) == "read_only":

        # 返回 review_policy_for_state 的访谈状态载荷。
        return "read_only_no_subagent_review"

    # 访谈中的写入流程尚未具备最终复核对象。
    return "design_interview_in_progress"


# 定义 state_path 的设计访谈状态处理入口。
def state_path(project: Path) -> Path:
    """返回设计访谈状态文件在项目内的固定位置。"""

    # 状态文件路径由共享常量控制，避免 CLI 和恢复流程写入不同位置。
    return project / STATE_PATH


# 定义 read_state 的设计访谈状态处理入口。
def read_state(project: Path) -> dict[str, Any] | None:
    """读取项目中的设计访谈状态。

    # 补充设计访谈状态代码段的职责说明。
    参数:
        project: 工作区根目录。

    # 补充设计访谈状态代码段的职责说明。
    返回:
        合法的状态字典；文件缺失、JSON 损坏或根类型不正确时返回 ``None``。
    """

    # 统一定位状态文件，保证读取路径与写入路径完全一致。
    path_state = state_path(project)  # 设计访谈状态文件

    # 没有状态文件表示当前没有可恢复访谈。
    if not path_state.exists():

        # 返回 read_state 的访谈状态载荷。
        return None

    # 状态读取失败时保持恢复流程可继续启动新访谈。
    try:

        # 保存 state data 映射，维持 read_state 的字段关系。
        dict_state_data = json.loads(path_state.read_text(encoding="utf-8"))  # 反序列化后的状态内容
    except Exception:

        # 返回 read_state 的访谈状态载荷。
        return None

    # 仅接受对象根节点，防止数组或标量 JSON 被误当成状态。
    return dict_state_data if isinstance(dict_state_data, dict) else None


# 定义 write_state 的设计访谈状态处理入口。
def write_state(project: Path, state: dict[str, Any]) -> Path:
    """把访谈状态写回项目，并刷新更新时间。

    # 补充设计访谈状态代码段的职责说明。
    参数:
        project: 工作区根目录。
        state: 将被持久化的状态字典；调用方持有的同一对象会同步获得 ``updated_at``。

    # 补充设计访谈状态代码段的职责说明。
    返回:
        实际写入的状态文件路径。
    
        数组契约:
            shape/维度: 本函数处理 AGENTS 状态、JSON 记录或文件路径，不接收数值数组，数组维度不适用。
            dtype/类型: 输入输出由 dict、list、str、Path 等 Python 业务类型约束，非 ndarray dtype。
            unit/单位: 无物理量单位，字段含义以 AGENTS 治理配置和状态文件 schema 为准。
    """

    # 状态目录可能在首次访谈时尚未创建。
    path_state = state_path(project)  # 设计访谈状态文件

    # 创建父目录只影响治理状态目录，不改变项目源码结构。
    path_state.parent.mkdir(exist_ok=True)

    # 每次持久化都刷新时间戳，用于恢复流程识别最新进度。
    state["updated_at"] = now_iso()  # 访谈状态值

    # 排序写入让状态 diff 稳定，便于 handoff 和恢复排查。
    path_state.write_text(json.dumps(state, indent=2, sort_keys=True), encoding="utf-8")

    # 返回路径方便 CLI 输出或测试断言。
    return path_state


