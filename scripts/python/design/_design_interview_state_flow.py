# 定义 advance_after_remote_gate 的设计访谈状态处理入口。
def advance_after_remote_gate(project: Path, state: dict[str, Any]) -> dict[str, Any]:
    """远程门禁完成后推进访谈到下一个问题组或收尾阶段。
    
    数组契约:
        shape/维度: 本函数处理 AGENTS 状态、JSON 记录或文件路径，不接收数值数组，数组维度不适用。
        dtype/类型: 输入输出由 dict、list、str、Path 等 Python 业务类型约束，非 ndarray dtype。
        unit/单位: 无物理量单位，字段含义以 AGENTS 治理配置和状态文件 schema 为准。
    """

    # 当前问题组索引用于判断是否已经完成全部访谈组。
    int_index = int(state.get("current_group_index", 0))  # 当前问题组索引

    # 接管模式在最后一组后交给接管收尾逻辑生成下一步状态。
    if str(state.get("mode", "interactive")) == "takeover" and int_index + 1 >= len(state.get("groups", [])):

        # 返回 advance_after_remote_gate 的访谈状态载荷。
        return complete_takeover(project, state, move_to_extra_requirements)

    # 仍有后续问题组时，继续进入普通收集阶段。
    if int_index + 1 < len(state.get("groups", [])):

        # 整理 advance_after_remote_gate 需要的 中间载荷 访谈状态。
        state["current_group_index"] = int_index + 1  # 访谈状态值

        # 整理 advance_after_remote_gate 需要的 中间载荷 访谈状态。
        state["status"] = "collecting_group"  # 访谈状态值
    else:

        # 返回 advance_after_remote_gate 的访谈状态载荷。
        return move_to_extra_requirements(project, state)

    # 持久化推进后的索引，避免远程门禁重复触发。
    write_state(project, state)

    # 返回下一组问题的交互 payload。
    return interactive_payload(project, state)


# 定义 refresh_remote_gate 的设计访谈状态处理入口。
def refresh_remote_gate(project: Path, state: dict[str, Any]) -> dict[str, Any] | None:
    """刷新远程服务器门禁状态，并在需要用户操作时返回交互 payload。

    # 补充设计访谈状态代码段的职责说明。
    返回 ``None`` 表示当前访谈未启用远程服务器治理，可继续普通问题组流程。
    
        数组契约:
            shape/维度: 本函数处理 AGENTS 状态、JSON 记录或文件路径，不接收数值数组，数组维度不适用。
            dtype/类型: 输入输出由 dict、list、str、Path 等 Python 业务类型约束，非 ndarray dtype。
            unit/单位: 无物理量单位，字段含义以 AGENTS 治理配置和状态文件 schema 为准。
    """

    # 远程门禁只在用户已启用远程服务器治理时生效。
    dict_answers = state.get("answers", {})  # 已收集回答

    # 非字典回答视为状态损坏，保持普通流程不触发远程依赖。
    if not isinstance(dict_answers, dict) or not use_remote_server_enabled(dict_answers):

        # 返回 refresh_remote_gate 的访谈状态载荷。
        return None

    # 门禁 payload 保留发现、选择和用户确认结果，避免重复询问。
    dict_gate = remote_gate_payload(state)  # 远程门禁状态

    # 依赖摘要判断 erie-remote-ssh 是否可用于后续服务器发现。
    dict_dependency = remote_dependency_summary()  # 远程技能依赖状态

    # 先写入依赖状态，方便缺依赖分支向用户展示安装信息。
    dict_gate.update(
        {
            "enabled": True,
            "dependency_required": True,
            "dependency_status": "installed" if dict_dependency["installed"] else "missing",
            "dependency_url": dict_dependency["url"],
            "install_specs": dict_dependency["install_specs"],
            "skill_dir": dict_dependency["skill_dir"],
        }
    )

    # 状态文件中的远程门禁字段是后续恢复远程流程的唯一依据。
    set_remote_gate_payload(state, dict_gate)

    # 依赖缺失时暂停问题组推进，等待用户安装或确认跳过。
    if not dict_dependency["installed"]:

        # 整理 refresh_remote_gate 需要的 中间载荷 访谈状态。
        state["status"] = (  # 访谈状态值
            "awaiting_remote_install_completion"  # 访谈状态值
            if dict_gate.get("install_confirmed")  # 访谈状态值
            else "awaiting_remote_install_confirmation"  # 访谈状态值
        )

        # 调用 write_state 处理 refresh_remote_gate。
        write_state(project, state)

        # 返回 refresh_remote_gate 的访谈状态载荷。
        return interactive_payload(project, state)

    # 已安装依赖后读取可用 SSH 配置状态。
    path_skill_dir = Path(dict_dependency["skill_dir"])  # erie-remote-ssh 依赖所在目录

    # 服务器发现结果决定是否进入配置补全或路由映射阶段。
    dict_discover, list_discover_errors = remote_discover(path_skill_dir)  # 远程发现结果和错误

    # 记录发现结果，恢复流程可直接展示相同证据。
    dict_gate["discover"] = dict_discover  # 访谈状态值

    # 更新门禁字段后再处理错误，保证错误页面也带有最新发现信息。
    set_remote_gate_payload(state, dict_gate)

    # 发现命令失败时保留当前阶段并把错误返回给调用方。
    if list_discover_errors:

        # 调用 write_state 处理 refresh_remote_gate。
        write_state(project, state)

        # 返回 refresh_remote_gate 的访谈状态载荷。
        return interactive_payload(project, state, errors=list_discover_errors)

    # 未配置或没有启用 SSH 时，要求用户先完成远程配置。
    if dict_discover.get("status") in {"not_configured", "no_enabled_ssh"}:

        # 整理 refresh_remote_gate 需要的 中间载荷 访谈状态。
        state["status"] = (  # 访谈状态值
            "awaiting_remote_configuration_completion"  # 访谈状态值
            if dict_gate.get("configuration_mode") in {"guided", "manual"}  # 访谈状态值
            else "awaiting_remote_configuration_confirmation"  # 访谈状态值
        )

        # 调用 write_state 处理 refresh_remote_gate。
        write_state(project, state)

        # 返回 refresh_remote_gate 的访谈状态载荷。
        return interactive_payload(project, state)

    # 配置可用后读取可选服务器列表，供用户映射任务路由。
    dict_choices, list_choice_errors = remote_choices(path_skill_dir)  # 远程服务器候选

    # 候选列表写入状态，避免下一次请求重复执行发现命令。
    dict_gate["choices"] = dict_choices  # 访谈状态值

    # 持久化选择候选，后续 payload 可直接渲染服务器选项。
    set_remote_gate_payload(state, dict_gate)

    # 候选读取失败时将错误返回给用户处理。
    if list_choice_errors:

        # 调用 write_state 处理 refresh_remote_gate。
        write_state(project, state)

        # 返回 refresh_remote_gate 的访谈状态载荷。
        return interactive_payload(project, state, errors=list_choice_errors)

    # 没有可选服务器时回到配置确认阶段，避免写入空路由。
    if dict_choices.get("status") != "available" or not dict_choices.get("servers"):

        # 整理 refresh_remote_gate 需要的 中间载荷 访谈状态。
        state["status"] = "awaiting_remote_configuration_confirmation"  # 访谈状态值

        # 调用 write_state 处理 refresh_remote_gate。
        write_state(project, state)

        # 返回 refresh_remote_gate 的访谈状态载荷。
        return interactive_payload(project, state, errors=["erie-remote-ssh choices did not return selectable servers"])

    # 依赖、配置和候选都可用后，等待用户为任务类型选择服务器路由。
    state["status"] = "awaiting_remote_server_route_mapping"  # 访谈状态值

    # 保存路由映射等待状态。
    write_state(project, state)

    # 返回包含服务器选项的交互 payload。
    return interactive_payload(project, state)


