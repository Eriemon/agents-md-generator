def is_active_state(state: dict[str, Any] | None) -> bool:
    """判断状态是否仍处于可继续的访谈流程。

    参数：state 为可空的访谈状态字典。
    返回：状态存在且尚未进入终态时为真。
    数组契约：shape、dtype 与 unit 均不适用，本函数处理 JSON 状态映射。
    """

    # 空状态和终态都不应阻塞新的访谈或只读检查。
    return bool(state) and str(state.get("status", "")) not in TERMINAL_STATUSES

