# 技能接管验证链必须覆盖结构、治理、文档和评估。
def _skill_validation_gates(project: Path, str_name: str) -> str:
    """构造技能接管完成后的验证命令链。

    参数：
        project: 当前工作区根目录。
        str_name: 接管目标技能名称。
    返回：
        使用分号连接且保持既有顺序的验证命令文本。
    """

    # 技能源码根用于所有 owner-repo 自举检查。
    str_skill_root = f"skills/{str_name}"  # 接管目标技能的仓库相对根目录。

    # 技能脚本前缀定位发布包内的 Python 治理入口。
    str_script_root = f"{str_skill_root}/scripts/python"  # 技能 Python 脚本目录。

    # AGENTS 验证命令同时检查仓库根规则和目标技能目录。
    str_verify_agents = script_command(  # AGENTS 治理验证命令。
        project,  # owner skill 所在项目根目录。
        "verify_agents.py",  # AGENTS 合同验证入口。
        ".",  # 当前项目验证目标。
        "--installed-skill-dir",  # 目标技能目录参数名。
        str_skill_root,  # 接管后的技能源码根。
    )

    # 文档验证确认 session、handoff 和 memory 状态一致。
    str_verify_docs = script_command(  # 文档治理验证命令。
        project,  # 文档状态所属的项目根目录。
        "manage_docs.py",  # 文档治理入口。
        "verify",  # 文档状态验证子命令。
        ".",  # 文档治理校验的当前目录。
    )

    # 技能评估命令覆盖画像与仓库事实的匹配程度。
    str_evaluate_skill = script_command(  # 技能评估命令。
        project,  # 技能画像所属的项目根目录。
        "evaluate_skill.py",  # 技能评估入口。
        str_skill_root,  # 待评估技能源码根。
        ".",  # 评估仓库事实的当前目录。
    )

    # 固定命令顺序保持历史控制画像和测试合同稳定。
    list_validation_commands = [
        f"python {str_script_root}/verify/quick_validate.py {str_skill_root}",  # 快速验证技能包结构。
        f"python {str_script_root}/verify/audit_skill.py {str_skill_root}",  # 审计技能治理合同。
        str_verify_agents,  # 验证根 AGENTS 与安装技能元数据。
        str_verify_docs,  # 验证文档治理状态。
        str_evaluate_skill,  # 运行技能画像评估。
    ]  # 接管技能的完整验证命令序列。

    # 控制画像继续使用单个文本字段承载命令链。
    return "; ".join(list_validation_commands)

