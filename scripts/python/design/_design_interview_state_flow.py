# 定义 validate_group_answers_with_optional 的设计访谈状态处理入口。
def validate_group_answers_with_optional(
    payload: dict[str, Any],
    expected_keys: list[str],
    required_keys: list[str],
) -> list[str]:

    # 收集 provided keys 访谈条目。
    set_provided_keys = set(payload)  # 访谈状态值

    # 整理 validate_group_answers_with_optional 需要的 expected 访谈状态。
    set_expected = set(expected_keys)  # 访谈状态值

    # 整理 validate_group_answers_with_optional 需要的 required 访谈状态。
    set_required = set(required_keys)  # 访谈状态值

    # 收集 errors 访谈条目。
    list_errors: list[str] = []  # 访谈状态值

    # 整理 validate_group_answers_with_optional 需要的 extra 访谈状态。
    extra = sorted(set_provided_keys - set_expected)  # 访谈状态值

    # 整理 validate_group_answers_with_optional 需要的 missing 访谈状态。
    missing = sorted(set_required - set_provided_keys)  # 访谈状态值

    # 校验 validate_group_answers_with_optional 的访谈状态分支。
    if extra:

        # 追加 validate_group_answers_with_optional 的访谈诊断。
        list_errors.append(f"out-of-group answers are not allowed for this step: {', '.join(extra)}")

    # 逐项检查 validate_group_answers_with_optional 访谈候选。
    for key in missing:

        # 追加 validate_group_answers_with_optional 的访谈诊断。
        list_errors.append(f"missing required answer: {key}")

    # 逐项检查 validate_group_answers_with_optional 访谈候选。
    for key in required_keys:

        # 校验 validate_group_answers_with_optional 的访谈状态分支。
        if key in OPTIONAL_EMPTY_KEYS and key in payload:

            # 分隔 validate_group_answers_with_optional 的控制流边界。
            continue

        # 校验 validate_group_answers_with_optional 的访谈状态分支。
        if key in payload and empty(payload[key]):

            # 追加 validate_group_answers_with_optional 的访谈诊断。
            list_errors.append(f"missing required answer: {key}")

    # 返回 validate_group_answers_with_optional 的访谈状态载荷。
    return list_errors

